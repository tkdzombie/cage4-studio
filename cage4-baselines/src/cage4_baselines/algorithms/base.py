"""Contract for research plugins; no simulator or Ground Truth dependency."""
from typing import Any, Mapping, Protocol
from ..core.types import PolicyInput

class Policy(Protocol):
    def act(self, inputs: Mapping[str, PolicyInput], training: bool = False) -> dict[str, int]: ...
    def observe(self, rewards: Mapping[str, float]) -> None: ...
    def update(self) -> dict[str, dict[str, float]]: ...
    def checkpoint(self) -> dict[str, Any]: ...
    def load(self, data: dict[str, Any]) -> None: ...
